    <div class="section">
        <h2>1. Ingreso al Sistema</h2>
        <p>Para acceder a la plataforma, siga estos pasos:</p>
        <ol>
            <li class="step">Seleccione su <strong>Tipo de Documento</strong> (Cédula, Tarjeta de Identidad, etc.).</li>
            <li class="step">Ingrese su <strong>Número de Documento</strong> sin puntos ni espacios.</li>
            <li class="step">Digite su <strong>Contraseña</strong> personal.</li>
            <li class="step">Haga clic en el botón <strong>"Ingresar"</strong>.</li>
        </ol>
        <div class="note">
            <strong>Nota:</strong> Si es la primera vez que ingresa, asegúrese de haberse registrado previamente o de tener sus credenciales proporcionadas por la entidad.
        </div>
    </div>

    <div class="section">
        <h2>2. Recuperación de Contraseña</h2>
        <p>Si ha olvidado su clave de acceso:</p>
        <ol>
            <li class="step">En la pantalla de inicio, haga clic en <strong>"¿Olvidaste tu contraseña?"</strong>.</li>
            <li class="step">Ingrese su tipo y número de documento en la ventana emergente.</li>
            <li class="step">Recibirá un correo electrónico con un enlace seguro.</li>
            <li class="step">Haga clic en el enlace y siga las instrucciones para crear una nueva contraseña.</li>
        </ol>
    </div>

    <div class="section">
        <h2>3. Registro de Nuevos Usuarios</h2>
        <p>Si aún no tiene cuenta:</p>
        <ol>
            <li class="step">Haga clic en <strong>"Crear cuenta nueva"</strong> en la pantalla de inicio.</li>
            <li class="step">Diligencie el formulario con sus datos personales (Nombre, Documento, Correo, etc.).</li>
            <li class="step">Cree una contraseña segura.</li>
            <li class="step">Al finalizar, podrá ingresar inmediatamente con sus nuevas credenciales.</li>
        </ol>
    </div>

    <div class="section">
        <h2>4. Panel Principal (Dashboard)</h2>
        <p>Una vez dentro del sistema, encontrará:</p>
        <ul>
            <li>Resumen de sus datos personales.</li>
            <li>Acceso a agendamiento de citas.</li>
            <li>Consulta de historia clínica y resultados.</li>
            <li>Actualización de datos de contacto.</li>
        </ul>
